using Microsoft.AspNetCore.Mvc.ApplicationModels;
using Molinex.Platform.Shared.Infrastructure.Interfaces.AspNetCore.Configuration.Extensions;

namespace Molinex.Platform.Shared.Infrastructure.Interfaces.AspNetCore.Configuration;

/// <summary>Replaces the <c>[controller]</c> route token with the kebab-case controller name.</summary>
public class KebabCaseRouteNamingConvention : IControllerModelConvention
{
    public void Apply(ControllerModel controller)
    {
        foreach (var selector in controller.Selectors)
            selector.AttributeRouteModel = ReplaceControllerTemplate(selector, controller.ControllerName);
        foreach (var selector in controller.Actions.SelectMany(action => action.Selectors))
            selector.AttributeRouteModel = ReplaceControllerTemplate(selector, controller.ControllerName);
    }

    private static AttributeRouteModel? ReplaceControllerTemplate(SelectorModel selector, string name)
    {
        return selector.AttributeRouteModel != null
            ? new AttributeRouteModel
            {
                Template = selector.AttributeRouteModel.Template?.Replace("[controller]", name.ToKebabCase())
            }
            : null;
    }
}
